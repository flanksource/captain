#!/usr/bin/env bash
# Publishes generated adapter schemas to the orphan `schemas` branch, gh-pages
# style: the branch holds only generated artifacts, under adapters/. The first
# run creates the branch. Usage: publish-schemas-branch.sh <generated-dir> <source-sha>
set -euo pipefail

generated=$(cd "$1" && pwd)
source_sha=$2
branch=schemas
worktree=$(mktemp -d)
trap 'git worktree remove --force "$worktree"' EXIT

test -s "$generated/native-resources.json"

if git ls-remote --exit-code --heads origin "$branch" >/dev/null; then
  git fetch --depth 1 origin "$branch"
  git worktree add -B "$branch" "$worktree" FETCH_HEAD
else
  git worktree add --detach "$worktree"
  git -C "$worktree" checkout --orphan "$branch"
  git -C "$worktree" rm -r -q --cached .
  git -C "$worktree" clean -f -d -x -q
fi

rm -rf "$worktree/adapters"
mkdir -p "$worktree/adapters"
cp "$generated"/*.json "$worktree/adapters/"
cat >"$worktree/README.md" <<'README'
# Captain generated schemas

Generated by the `Adapter schemas` workflow from `main`; never edit by hand.
`adapters/native-resources.json` is the native provider resource catalog the
Captain web UI loads. `adapters/<provider>.json` are the full provider
configuration schemas it is projected from. See docs/adapter-resource-schemas.md
on `main` for sources, patches and regeneration.
README

git -C "$worktree" add -A
if git -C "$worktree" diff --cached --quiet; then
  echo "schemas branch already matches ${source_sha}"
  exit 0
fi
git -C "$worktree" -c user.name="github-actions[bot]" -c user.email="41898282+github-actions[bot]@users.noreply.github.com" \
  commit -q -m "chore(schemas): publish adapter schemas from ${source_sha}"
git -C "$worktree" push origin "$branch"
